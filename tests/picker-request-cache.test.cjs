const test = require('node:test');
const assert = require('node:assert/strict');
const { createHarness } = require('./services-test-harness.cjs');
const load = () => createHarness().load('controls/pickers/picker-request-cache.internal.ts');
test('memory cache shares inflight requests, retains failures and expires only on demand', async () => {
  const { createPickerRequestCache } = load();
  let now = 0, calls = 0, finish;
  const cache = createPickerRequestCache({}, { now: () => now });
  const pending = () => { calls++; return new Promise(resolve => { finish = resolve; }); };
  const first = cache.request('sites:q', pending);
  const second = cache.request('sites:q', pending);
  assert.equal(first, second);
  await Promise.resolve(); finish(['a']);
  assert.deepEqual(await first, ['a']);
  assert.deepEqual(await cache.request('sites:q', pending), ['a']);
  assert.equal(calls, 1);
  now = 300001;
  assert.equal(calls, 1);
  assert.equal(await cache.request('sites:q', async () => { calls++; return ['b']; }), (await cache.request('sites:q', pending)));
  const failure = new Error('denied');
  let failures = 0;
  for (let i = 0; i < 2; i++) await assert.rejects(cache.request('groups:q', async () => { failures++; throw failure; }), failure);
  assert.equal(failures, 1);
  cache.invalidate('groups:');
  assert.deepEqual(await cache.request('groups:q', async () => ['ok']), ['ok']);
});
test('invalidated or disposed inflight work cannot seed the next generation', async () => {
  const { createPickerRequestCache } = load();
  const cache = createPickerRequestCache({});
  let finish;
  const old = cache.request('a:q', () => new Promise(resolve => { finish = resolve; }));
  await Promise.resolve();
  cache.invalidate('a:');
  const fresh = await cache.request('a:q', async () => 'new');
  finish('old');
  assert.equal(await old, 'old');
  assert.equal(await cache.request('a:q', async () => 'wrong'), fresh);
  cache.dispose();
  await assert.rejects(cache.request('a:q', async () => 'wrong'), /disposed/);
  const other = createPickerRequestCache({});
  assert.equal(await other.request('a:q', async () => 'other owner'), 'other owner');
});
test('settled LRU is bounded and touching a cached request keeps it resident', async () => {
  const { createPickerRequestCache } = load();
  const cache = createPickerRequestCache({});
  for (let i = 0; i < 128; i++) await cache.request(String(i), async () => i);
  await cache.request('0', async () => 'wrong');
  await cache.request('128', async () => 128);
  assert.equal(await cache.request('0', async () => 'wrong'), 0);
  assert.equal(await cache.request('1', async () => 'reloaded'), 'reloaded');
});
test('shared dependent metadata is deduplicated but invalidated with every source that uses it', async () => {
  const cache = load().createPickerRequestCache({});
  let calls = 0;
  const fail = async () => { calls++; throw new Error('503'); };
  await assert.rejects(cache.request('target:list', fail, 'fields:'), /503/);
  await assert.rejects(cache.request('target:list', fail, 'views:'), /503/);
  assert.equal(calls, 1);
  cache.invalidate('views:');
  assert.equal(await cache.request('target:list', async () => 'recovered', 'fields:'), 'recovered');
});

test('peek exposes only current request provenance without loading, refreshing TTL or LRU order', async () => {
  const { createPickerRequestCache } = load();
  let now = 0, calls = 0;
  const cache = createPickerRequestCache({}, { now: () => now });
  assert.equal(cache.peek('missing'), undefined);
  const pending = cache.request('first', async () => ++calls);
  assert.equal(cache.peek('first'), pending, 'inflight and settled entries retain the same token');
  assert.equal(await pending, 1);
  now = 299999;
  assert.equal(cache.peek('first'), pending);
  now = 300000;
  assert.equal(cache.peek('first'), undefined, 'peek does not extend TTL');
  assert.equal(calls, 1, 'peeking never starts another load');
  const fresh = cache.request('first', async () => ++calls);
  assert.notEqual(fresh, pending);
  await fresh;
  for (let i = 0; i < 127; i++) await cache.request(String(i), async () => i);
  assert.equal(cache.peek('first'), fresh);
  await cache.request('overflow', async () => 'overflow');
  assert.equal(cache.peek('first'), undefined, 'peek does not change LRU order');
  const failure = cache.request('failure', async () => { throw new Error('denied'); });
  await assert.rejects(failure, /denied/);
  assert.equal(cache.peek('failure'), failure, 'failed entries retain their provenance until invalidated');
  cache.invalidate('failure');
  assert.equal(cache.peek('failure'), undefined);
  cache.dispose();
  assert.equal(cache.peek('overflow'), undefined);
});
test('peek atomically registers refresh dependencies only for live or in-flight entries', async () => {
  const { createPickerRequestCache } = load();
  let now = 0, finish;
  const cache = createPickerRequestCache({}, { now: () => now });
  const pending = cache.request('catalog', () => new Promise(resolve => { finish = resolve; }), 'catalog-source:');
  assert.equal(cache.peek('catalog', 'verification:'), pending);
  cache.invalidate('verification:');
  assert.equal(cache.peek('catalog'), undefined, 'a reused in-flight request depends on verification refresh');
  await Promise.resolve(); finish('old'); await pending;
  assert.equal(cache.peek('catalog'), undefined, 'the invalidated completion cannot seed the cache');
  const settled = cache.request('catalog', async () => 'current'); await settled;
  assert.equal(cache.peek('catalog', 'settled-verification:'), settled);
  cache.invalidate('settled-verification:');
  assert.equal(cache.peek('catalog'), undefined, 'a reused settled request depends on verification refresh');
  const expiring = cache.request('catalog', async () => 'expiring'); await expiring;
  now = 299999;
  assert.equal(cache.peek('catalog', 'active:'), expiring);
  now = 300000;
  assert.equal(cache.peek('catalog', 'expired:'), undefined, 'dependency registration never extends TTL');
  const fresh = cache.request('catalog', async () => 'fresh'); await fresh;
  cache.invalidate('expired:');
  assert.equal(cache.peek('catalog'), fresh, 'an expired inspection never registers a dependency');
  assert.equal(cache.peek('missing', 'missing:'), undefined);
  const added = cache.request('missing', async () => 'added'); await added;
  cache.invalidate('missing:');
  assert.equal(cache.peek('missing'), added, 'an absent inspection never registers a dependency');
});
