const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const vm = require('node:vm');
const ts = require('typescript');
const { spawnSync } = require('node:child_process');
const test = require('node:test');
const config = require('../scripts/documentation.config.cjs');
const fixture = path.join(__dirname, 'fixtures/documentation/artifact-set');
const outputRoot = 'apps/spfx-react-toolkit-test/src/webparts/spFxReactToolkitTest/components/generated/jsdoc-examples';
const marker = '// Generated by scripts/executable-examples.cjs. Do not edit.';
function api() {
  assert.ok(fs.existsSync(path.join(__dirname, '../scripts/executable-examples.cjs')), 'executable artifact generator must exist');
  return require('../scripts/executable-examples.cjs');
}
function writer() { return require('../scripts/generated-artifacts.cjs'); }
function temporary(t, executable = true) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'executable-artifacts-'));
  fs.cpSync(fixture, root, { recursive: true });
  fs.symlinkSync(path.resolve(__dirname, '../node_modules'), path.join(root, 'node_modules'), 'dir');
  if (executable) {
    const doc = fs.readFileSync(path.join(__dirname, 'fixtures/executable-examples/cases/artifact-count.jsdoc'), 'utf8');
    fs.writeFileSync(path.join(root, config.sourceRoot, 'index.ts'), doc + 'export function count(value: number): number { return value; }\n');
    const file = path.join(root, config.tsconfig);
    const project = JSON.parse(fs.readFileSync(file, 'utf8'));
    project.compilerOptions.jsx = 'react';
    fs.writeFileSync(file, JSON.stringify(project));
  }
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  return root;
}
function snapshot(root) {
  const result = {};
  function visit(file, route) {
    const stat = fs.lstatSync(file);
    result[route] = { mtime: stat.mtimeMs, kind: stat.isDirectory() ? 'directory' : stat.isSymbolicLink() ? 'symlink' : 'file' };
    if (stat.isDirectory()) for (const name of fs.readdirSync(file).sort()) visit(path.join(file, name), route + '/' + name);
    else if (stat.isFile()) result[route].hash = crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
  }
  visit(root, '.');
  return result;
}
function catalogue(artifacts) {
  const source = artifacts[outputRoot + '/catalogue.ts'];
  const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
  const exports = {};
  vm.runInNewContext(js, { exports });
  return { source, ...exports };
}
function moduleRoutes(artifacts) { return Object.keys(artifacts).filter(route => route.endsWith('.tsx')); }
function apply(root, expected, mode) { return writer().applyGeneratedArtifacts(root, expected, mode, api().executableExamplesPolicy(config)); }

test('emits exact source bytes, literal lazy imports and one feature with source-ordered scenarios', t => {
  const root = temporary(t);
  const before = snapshot(root);
  const artifacts = api().generateExecutableArtifacts(root, config);
  assert.deepEqual(snapshot(root), before);
  const { buildValidatedDocumentationContext } = require('../scripts/documentation-context.cjs');
  const context = buildValidatedDocumentationContext(root, config);
  const cat = catalogue(artifacts);
  assert.equal(moduleRoutes(artifacts).length, 2);
  assert.deepEqual(Array.from(cat.executableExamples, entry => entry.title), ['Z first scenario', 'A second scenario']);
  assert.equal(cat.executableGroups.length, 1);
  assert.equal(cat.executableGroups[0].key, 'helpers');
  assert.equal(cat.executableGroups[0].title, 'Helper e stili');
  assert.equal(cat.executableGroups[0].features.length, 1);
  const feature = cat.executableGroups[0].features[0];
  assert.equal(feature.title, 'count');
  assert.deepEqual(Array.from(feature.scenarios, entry => entry.id), Array.from(cat.executableExamples, entry => entry.id));
  for (const entry of cat.executableExamples) {
    const example = context.model.examples.find(item => item.ownerKey === entry.ownerKey && item.title === entry.title);
    assert.equal(artifacts[outputRoot + '/' + entry.id + '.tsx'], marker + '\n' + example.code);
    assert.match(cat.source, new RegExp('import\\("\\./' + entry.id + '"\\)'));
    assert.equal(typeof entry.load, 'function');
    assert.equal(entry.metadata.host, 'none');
  }
  assert.match(cat.source, /export interface ExecutableExampleEntry/);
  assert.match(cat.source, /export interface ExecutableExampleProps/);
  assert.match(cat.source, /import type .*React/);
  const { renderExecutableExamples } = require('../scripts/executable-examples-render.cjs');
  const { collectExecutableExamples } = require('../scripts/executable-examples-model.cjs');
  const projected = collectExecutableExamples(root, context.model, config).examples;
  const first = projected.find(entry => entry.title === 'Z first scenario');
  const second = projected.find(entry => entry.title === 'A second scenario');
  const other = { ...first, id: 'a'.repeat(64), ownerKey: 'other', featureKey: 'other', featureTitle: 'Another', groupKey: 'controls', groupRoute: 'docs/api/controls/other.md' };
  const rendered = renderExecutableExamples([first, other, second]);
  const reordered = renderExecutableExamples([other, first, second]);
  assert.deepEqual(rendered, reordered);
  const ordered = catalogue(rendered);
  assert.deepEqual(Array.from(ordered.executableGroups, group => group.key), ['controls', 'helpers']);
  assert.deepEqual(Array.from(ordered.executableGroups[1].features[0].scenarios, entry => entry.title), ['Z first scenario', 'A second scenario']);
  assert.throws(() => renderExecutableExamples([first, { ...second, id: first.id }]), /collision|duplicate/i);
});

test('body changes retain identity; title changes create a new route and an owned orphan', t => {
  const root = temporary(t);
  const initial = api().generateExecutableArtifacts(root, config);
  apply(root, initial, 'write');
  const file = path.join(root, config.sourceRoot, 'index.ts');
  fs.writeFileSync(file, fs.readFileSync(file, 'utf8').replace('count(3)', 'count(4)'));
  const body = api().generateExecutableArtifacts(root, config);
  assert.deepEqual(Object.keys(body), Object.keys(initial));
  assert.equal(writer().compareGeneratedArtifacts(root, body, api().executableExamplesPolicy(config)).changed.length, 1);
  fs.writeFileSync(file, fs.readFileSync(file, 'utf8').replace('Z first scenario', 'Renamed scenario'));
  const renamed = api().generateExecutableArtifacts(root, config);
  const diff = writer().compareGeneratedArtifacts(root, renamed, api().executableExamplesPolicy(config));
  assert.equal(diff.missing.length, 1);
  assert.equal(diff.orphan.length, 1);
  assert.ok(diff.orphan[0].endsWith('.tsx'));
});

test('check and preflight are read-only for missing, changed and orphan sets; writes preserve unchanged mtimes and manual orphans', t => {
  const root = temporary(t);
  const artifacts = api().generateExecutableArtifacts(root, config);
  let before = snapshot(root);
  writer().preflightGeneratedArtifacts(root, artifacts, api().executableExamplesPolicy(config));
  assert.equal(apply(root, artifacts, 'check').ok, false);
  assert.deepEqual(snapshot(root), before);
  apply(root, artifacts, 'write');
  const modules = moduleRoutes(artifacts);
  fs.unlinkSync(path.join(root, modules[0]));
  fs.appendFileSync(path.join(root, modules[1]), '// stale\n');
  fs.writeFileSync(path.join(root, outputRoot, 'orphan.tsx'), marker + '\nexport {};\n');
  const manual = '// Manual\n' + marker + '\n';
  fs.writeFileSync(path.join(root, outputRoot, 'manual.tsx'), manual);
  before = snapshot(root);
  const result = apply(root, artifacts, 'check');
  assert.deepEqual(result.diff, { missing: [modules[0]], changed: [modules[1]], orphan: [outputRoot + '/orphan.tsx'] });
  assert.deepEqual(snapshot(root), before);
  assert.equal(apply(root, artifacts, 'write').ok, true);
  assert.equal(fs.readFileSync(path.join(root, outputRoot, 'manual.tsx'), 'utf8'), manual);
  assert.equal(fs.existsSync(path.join(root, outputRoot, 'orphan.tsx')), false);
  assert.equal(snapshot(root)['./' + outputRoot + '/catalogue.ts'].mtime, before['./' + outputRoot + '/catalogue.ts'].mtime);
  const unchanged = snapshot(root);
  assert.equal(apply(root, artifacts, 'write').ok, true);
  assert.deepEqual(snapshot(root), unchanged);
});

test('rejects traversal, symlinks, portable collisions, shared files and manual expected destinations before writes', t => {
  const root = temporary(t);
  const artifacts = api().generateExecutableArtifacts(root, config);
  const content = marker + '\nexport {};\n';
  for (const expected of [
    { '../escape.tsx': content }, { [outputRoot + '/../escape.tsx']: content }, { 'docs/api/fake.tsx': content },
    { [outputRoot + '/A.tsx']: content, [outputRoot + '/a.tsx']: content },
    { [outputRoot + '/leaf.tsx']: content, [outputRoot + '/leaf.tsx/child.tsx']: content },
    { [outputRoot + '/bad.tsx']: 'no final newline' },
  ]) {
    const before = snapshot(root);
    assert.throws(() => apply(root, expected, 'write'), /path|destination|collision|ancestor|canonical/i);
    assert.deepEqual(snapshot(root), before);
  }
  fs.mkdirSync(path.join(root, outputRoot), { recursive: true });
  const routes = moduleRoutes(artifacts);
  fs.writeFileSync(path.join(root, routes[0]), content);
  fs.linkSync(path.join(root, routes[0]), path.join(root, routes[1]));
  let before = snapshot(root);
  assert.throws(() => apply(root, artifacts, 'write'), /share a file/i);
  assert.deepEqual(snapshot(root), before);
  fs.unlinkSync(path.join(root, routes[1]));
  fs.unlinkSync(path.join(root, routes[0]));
  fs.symlinkSync(path.join(root, 'README.md'), path.join(root, routes[0]));
  before = snapshot(root);
  assert.throws(() => apply(root, artifacts, 'check'), /symbolic link|symlink/i);
  assert.deepEqual(snapshot(root), before);
  fs.unlinkSync(path.join(root, routes[0]));
  fs.writeFileSync(path.join(root, routes[0]), '// Manual module\n');
  before = snapshot(root);
  for (const mode of ['write', 'check']) assert.throws(() => apply(root, artifacts, mode), /manual|unowned|owned/i);
  assert.throws(() => writer().preflightGeneratedArtifacts(root, artifacts, api().executableExamplesPolicy(config)), /manual|unowned|owned/i);
  assert.deepEqual(snapshot(root), before);
});

