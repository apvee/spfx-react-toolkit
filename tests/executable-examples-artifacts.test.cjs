test('standalone CLI has independent validated modes, check precedence and a valid empty catalogue', t => {
  api();
  assert.throws(() => api().runCli(['--unknown'], {}), /Usage/);
  assert.throws(() => api().runCli(['--check'], { TOOLKIT_EXAMPLES_MODE: 'invalid' }), /TOOLKIT_EXAMPLES_MODE/);
  const root = temporary(t, false);
  fs.cpSync(path.resolve(__dirname, '../scripts'), path.join(root, 'scripts'), { recursive: true });
  fs.copyFileSync(path.resolve(__dirname, '../packages/spfx-react-toolkit/tsdoc.json'), path.join(root, config.packageRoot, 'tsdoc.json'));
  fs.copyFileSync(path.resolve(__dirname, '../package-lock.json'), path.join(root, 'package-lock.json'));
  function cli(args, env = {}) {
    return spawnSync(process.execPath, [path.join(root, 'scripts/executable-examples.cjs'), ...args], { encoding: 'utf8', env: { ...process.env, TOOLKIT_EXAMPLES_MODE: 'write', ...env } });
  }
  const before = snapshot(root);
  const missing = cli(['--check'], { TOOLKIT_EXAMPLES_MODE: 'write' });
  assert.equal(missing.status, 1, missing.stderr);
  assert.match(missing.stderr, /Stale generated executable examples/);
  assert.deepEqual(snapshot(root), before);
  const write = cli([], { TOOLKIT_DOCS_MODE: 'invalid' });
  assert.equal(write.status, 0, write.stderr);
  const current = snapshot(root);
  const check = cli([], { TOOLKIT_EXAMPLES_MODE: 'check' });
  assert.equal(check.status, 0, check.stderr);
  assert.deepEqual(snapshot(root), current);
  const empty = catalogue(api().generateExecutableArtifacts(root, config));
  assert.equal(empty.executableExamples.length, 0);
  assert.equal(empty.executableGroups.length, 0);
});

