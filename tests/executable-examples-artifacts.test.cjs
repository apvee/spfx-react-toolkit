test('both compiler consumers reject generated executable source/config inputs including symlink aliases', t => {
  const { buildValidatedDocumentationContext } = require('../scripts/documentation-context.cjs');
  const { buildApiGraph } = require('../scripts/documentation-model.cjs');
  const { checkDocumentationExamples } = require('../scripts/documentation-examples.cjs');
  for (const kind of ['source', 'source-alias', 'config', 'config-alias']) {
    const root = temporary(t, false);
    const context = buildValidatedDocumentationContext(root, config);
    fs.mkdirSync(path.join(root, outputRoot), { recursive: true });
    const isConfig = kind.startsWith('config');
    const generated = path.join(root, outputRoot, isConfig ? 'base.json' : 'input.ts');
    fs.writeFileSync(generated, isConfig ? '{"compilerOptions":{"strict":true}}\n' : 'export const amount = 4;\n');
    let input = generated;
    if (kind.endsWith('alias')) {
      input = path.join(root, isConfig ? 'generated-base.json' : 'generated-input.ts');
      fs.symlinkSync(generated, input);
    }
    if (isConfig) {
      const file = path.join(root, config.tsconfig);
      const project = JSON.parse(fs.readFileSync(file, 'utf8'));
      project.extends = '../../' + path.relative(root, input).split(path.sep).join('/');
      fs.writeFileSync(file, JSON.stringify(project));
    } else {
      const file = path.join(root, config.sourceRoot, 'index.ts');
      const specifier = '../../../' + path.relative(root, input).split(path.sep).join('/').replace(/\.ts$/, '');
      fs.writeFileSync(file, `import { amount } from ${JSON.stringify(specifier)};\n` + fs.readFileSync(file, 'utf8').replace('return value;', 'return amount;'));
    }
    const before = snapshot(root);
    for (const consume of [() => buildApiGraph(root, config).diagnostics, () => checkDocumentationExamples(root, context.model, config)]) {
      assert.throws(() => {
        const diagnostics = consume();
        if (diagnostics.length) throw new Error(diagnostics.map(item => item.code + ': ' + item.message).join('\n'));
      }, /forbidden|outside|not admitted|TS2307|Cannot find module|Cannot read file/i, kind);
    }
    assert.deepEqual(snapshot(root), before);
  }
});
