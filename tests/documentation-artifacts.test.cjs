test('R1 rejects forbidden transitive compiler source/config closures before outputs change', t => {
  const cases = [
    ['evidence import', '.docs/input.ts', 'export const amount = 3;\n', 'import'],
    ['old own lib', config.packageRoot + '/lib/input.d.ts', 'export declare const amount: number;\n', 'import'],
    ['generated public tree', 'docs/api/input.ts', 'export const amount = 3;\n', 'import'],
    ['configured output tree', 'generated/input.ts', 'export const amount = 3;\n', 'outDir'],
    ['configured bundled output', 'generated/output.js', 'export const amount = 3;\n', 'outFile'],
    ['evidence config extension', '.docs/base.json', '{"compilerOptions":{"strict":true}}\n', 'extends'],
    ['compiled config extension', config.packageRoot + '/lib/base.json', '{"compilerOptions":{"strict":true}}\n', 'extends'],
    ['evidence explicit include', '.docs/ambient.d.ts', 'declare const secret: number;\n', 'include'],
  ];
  for (const [label, route, text, kind] of cases) {
    const root = temporary(t);
    const artifacts = api().generateArtifacts(root, config);
    api().applyArtifacts(root, artifacts, 'write');
    fs.mkdirSync(path.dirname(path.join(root, route)), { recursive: true });
    fs.writeFileSync(path.join(root, route), text);
    const configFile = path.join(root, config.tsconfig);
    const project = JSON.parse(fs.readFileSync(configFile, 'utf8'));
    if (kind === 'extends') {
      const relative = path.relative(path.dirname(configFile), path.join(root, route));
      project.extends = relative.startsWith('.') ? relative : './' + relative;
    }
    else if (kind === 'include') project.include.push(path.relative(path.dirname(configFile), path.join(root, route)));
    else {
      if (kind === 'outDir') project.compilerOptions.outDir = path.relative(path.dirname(configFile), path.join(root, 'generated'));
      if (kind === 'outFile') Object.assign(project.compilerOptions, { allowJs: true, module: 'amd', outFile: path.relative(path.dirname(configFile), path.join(root, route)) });
      fs.mkdirSync(path.join(root, 'shared'));
      fs.writeFileSync(path.join(root, 'shared/bridge.ts'), `export { amount } from ${JSON.stringify('../' + route.replace(/(?:\.d)?\.[tj]s$/, ''))};\n`);
      const source = path.join(root, config.sourceRoot, 'index.ts');
      fs.writeFileSync(source, 'import { amount } from "../../../shared/bridge";\n' + fs.readFileSync(source, 'utf8').replace('return value;', 'return amount;'));
    }
    fs.writeFileSync(configFile, JSON.stringify(project));
    const before = snapshot(root);
    assert.throws(() => api().generateArtifacts(root, config), /forbidden|outside|not admitted|TS2307|Cannot find module|not found/i, label);
    assert.deepEqual(snapshot(root), before, label);
  }
});
