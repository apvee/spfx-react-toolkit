function snapshot(root) {
  const result = { '.': { mtime: fs.lstatSync(root).mtimeMs, kind: 'directory' } };
  function visit(directory) {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const absolute = path.join(directory, entry.name);
      const route = path.relative(root, absolute).split(path.sep).join('/');
      const stat = fs.lstatSync(absolute);
      result[route] = { mtime: stat.mtimeMs, kind: entry.isDirectory() ? 'directory' : entry.isSymbolicLink() ? 'symlink' : 'file' };
      if (entry.isDirectory()) visit(absolute);
      else if (entry.isFile()) result[route].hash = crypto.createHash('sha256').update(fs.readFileSync(absolute)).digest('hex');
    }
  }
  visit(root);
  return result;
}
