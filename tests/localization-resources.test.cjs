test('rejects dangling external output file symlinks before any output mutation', t => {
  const f = fixture(t); const outside = fs.mkdtempSync(path.join(os.tmpdir(), 'localization-dangling-'));
  t.after(() => fs.rmSync(outside, { recursive: true, force: true }));
  const destination = path.join(outside, 'not-yet-created.js');
  const output = path.join(f.root, 'lib/controls/mini/loc/en-us.js');
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.symlinkSync(destination, output);
  assert.throws(() => emitLocalizedResources(f.root), /output.*symlink/i);
  assert.equal(fs.existsSync(destination), false);
  assert.equal(fs.existsSync(path.join(f.root, 'lib/controls/mini/loc/it-it.js')), false);
  assert.equal(fs.lstatSync(output).isSymbolicLink(), true);
});
