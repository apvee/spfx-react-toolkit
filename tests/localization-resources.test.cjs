'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');
const { spawnSync } = require('node:child_process');
const { buildInventory, validateResources, emitLocalizedResources } = require('../scripts/localization-resources.cjs');
const script = path.resolve(__dirname, '../scripts/localization-resources.cjs');
const marker = '// Generated by scripts/localization-resources.cjs; do not edit.\n';
function write(root, name, value) {
  const target = path.join(root, name); fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, typeof value === 'string' ? value : JSON.stringify(value, undefined, 2) + '\n');
}
function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'toolkit-localization-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const config = { schemaVersion: 1, locales: ['it-IT', 'en-US'], families: [{
    family: 'mini', id: 'ApveeSpfxReactToolkitMiniStrings', sourceDirectory: 'src/controls/mini/localization/resources',
    resourceType: { path: 'src/controls/mini/localization/mini-resource.types.internal.ts', export: 'MiniResource' },
    outputPattern: 'lib/controls/mini/loc/{locale}.js', templates: { greetingTemplate: ['name'] },
    arrays: { 'calendar.months': 12, 'calendar.days': 7 }, plurals: { count: { tokens: ['count'] } }
  }] };
  const resource = JSON.parse(fs.readFileSync(path.join(__dirname, 'fixtures/localization-resources/mini-en-US.json'), 'utf8'));
  const italian = JSON.parse(fs.readFileSync(path.join(__dirname, 'fixtures/localization-resources/mini-it-IT.json'), 'utf8'));
  write(root, config.families[0].resourceType.path, fs.readFileSync(path.join(__dirname, 'fixtures/localization-resources/mini-resource.types.internal.ts'), 'utf8'));
  const save = () => {
    write(root, 'localization/resources.config.json', config);
    write(root, `${config.families[0].sourceDirectory}/en-US.json`, resource);
    write(root, `${config.families[0].sourceDirectory}/it-IT.json`, { ...resource, count: { ...resource.count, many: italian.count.many } });
  };
  save(); return { root, config, resource, save };
}
function command(root, mode) { return spawnSync(process.execPath, [script, mode, '--package-root', root], { encoding: 'utf8' }); }
test('inventory sorts resource IDs and cultures deterministically without creating outputs', t => {
  const f = fixture(t); f.config.families.push({ ...f.config.families[0], family: 'alpha', id: 'ApveeSpfxReactToolkitAlphaStrings', outputPattern: 'lib/controls/alpha/loc/{locale}.js' }); f.save();
  assert.deepEqual(buildInventory(f.root), { schemaVersion: 1, resources: [
    { id: 'ApveeSpfxReactToolkitAlphaStrings', path: 'lib/controls/alpha/loc/{locale}.js', locales: ['en-US', 'it-IT'] },
    { id: 'ApveeSpfxReactToolkitMiniStrings', path: 'lib/controls/mini/loc/{locale}.js', locales: ['en-US', 'it-IT'] }
  ] });
  assert.equal(fs.existsSync(path.join(f.root, 'lib')), false);
});
for (const [name, mutate, error] of [
  ['duplicate IDs', f => f.config.families.push({ ...f.config.families[0] }), /duplicate.*ID/i],
  ['path traversal', f => { f.config.families[0].sourceDirectory = '../outside'; }, /package.relative|traversal|bounded/i],
  ['output path without locale', f => { f.config.families[0].outputPattern = 'lib/controls/mini/loc/en-us.js'; }, /exactly one.*locale/i],
  ['missing en-US', f => { f.config.locales = ['it-IT']; }, /en-US/],
  ['duplicate cultures', f => { f.config.locales.push('en-US'); }, /duplicate.*locale/i],
  ['unsupported ICU locale', f => { f.config.locales.push('zz-ZZ'); }, /ICU|plural.*locale/i],
  ['missing fields', f => { delete f.resource.title; }, /title.*missing|missing.*title/i],
  ['extra fields', f => { f.resource.unexpected = 'extra'; }, /unexpected|known properties/],
  ['wrong scalar types', f => { f.resource.title = 42; }, /number.*string|string.*number/],
  ['wrong array types', f => { f.resource.calendar.months = 'months'; }, /months|string.*readonly.*string|array/i],
  ['calendar month length', f => { f.resource.calendar.months.pop(); }, /calendar.months.*12/],
  ['calendar weekday length', f => { f.resource.calendar.days.push('extra'); }, /calendar.days.*7/],
  ['blank labels', f => { f.resource.title = '  '; }, /title.*nonblank|blank.*title/i],
  ['missing placeholders', f => { f.resource.greetingTemplate = 'Hello'; }, /greetingTemplate.*name/],
  ['duplicate placeholders', f => { f.resource.greetingTemplate = '{name} {name}'; }, /greetingTemplate.*name/],
  ['unrecognized placeholders', f => { f.resource.greetingTemplate = '{name} {extra}'; }, /greetingTemplate.*extra|greetingTemplate.*tokens/i],
  ['unsupported plural branches', f => { f.resource.count.two = '{count} items'; }, /count.*two|plural.*branches/i],
  ['missing plural branches', f => { delete f.resource.count.one; }, /count.*one|plural.*branches/i],
  ['missing plural placeholders', f => { f.resource.count.one = 'item'; }, /count.one.*count/]
]) test(`rejects ${name} before emitting any files`, t => {
  const f = fixture(t); mutate(f); f.save();
  assert.throws(() => emitLocalizedResources(f.root), error);
  assert.equal(fs.existsSync(path.join(f.root, 'lib')), false);
});
test('validator returns direct contracts and all validated culture data for later harnesses', t => {
  const f = fixture(t); const result = validateResources(f.root);
  assert.equal(result[0].id, 'ApveeSpfxReactToolkitMiniStrings');
  assert.equal(result[0].catalogs['en-US'].title, 'Example');
  assert.equal(result[0].pluralLocales['it-IT'], 'it-IT');
});
test('emits deterministic anonymous AMD containing only data and literal caller substitutions', t => {
  const f = fixture(t); f.resource.greetingTemplate = 'Hello {name} </script>\u2028'; f.save();
  emitLocalizedResources(f.root);
  const file = path.join(f.root, 'lib/controls/mini/loc/en-us.js'); const before = fs.readFileSync(file, 'utf8');
  let data; const context = { define(deps, factory) { assert.deepEqual(Array.from(deps), []); data = factory(); } };
  vm.runInNewContext(before, context);
  assert.deepEqual(Object.keys(context), ['define']);
  assert.equal(data.__locale, 'en-US'); assert.equal(data.title, 'Example');
  const input = "$& $' {braces} {name}";
  assert.equal(data.greetingTemplate.replace(/\{name\}/g, () => input), `Hello ${input} </script>\u2028`);
  emitLocalizedResources(f.root); assert.equal(fs.readFileSync(file, 'utf8'), before);
});
test('removes only previously generated stale locale assets in current managed family directories', t => {
  const f = fixture(t);
  write(f.root, 'lib/controls/mini/loc/fr-fr.js', marker + 'stale');
  write(f.root, 'lib/controls/mini/loc/custom.js', 'caller content');
  write(f.root, 'lib/controls/unmanaged/loc/fr-fr.js', marker + 'not owned');
  emitLocalizedResources(f.root);
  assert.equal(fs.existsSync(path.join(f.root, 'lib/controls/mini/loc/fr-fr.js')), false);
  assert.equal(fs.readFileSync(path.join(f.root, 'lib/controls/mini/loc/custom.js'), 'utf8'), 'caller content');
  assert.equal(fs.existsSync(path.join(f.root, 'lib/controls/unmanaged/loc/fr-fr.js')), true);
});
test('explicit inventory write and check detect drift without check mutations', t => {
  const f = fixture(t);
  assert.equal(command(f.root, '--write-inventory').status, 0);
  const inventoryPath = path.join(f.root, 'localization/resources.json'); const bytes = fs.readFileSync(inventoryPath, 'utf8');
  assert.equal(command(f.root, '--check-inventory').status, 0);
  write(f.root, 'localization/resources.json', bytes.replace('MiniStrings', 'StaleStrings'));
  const stale = fs.readFileSync(inventoryPath, 'utf8'); const check = command(f.root, '--check-inventory');
  assert.equal(check.status, 1); assert.match(check.stderr, /stale|drift/i); assert.equal(fs.readFileSync(inventoryPath, 'utf8'), stale);
  assert.equal(fs.existsSync(path.join(f.root, 'lib')), false);
});
