'use strict';
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const generatedMarker = '// Generated by scripts/localization-resources.cjs; do not edit.\n';
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0;

/**
 * Private build descriptor, version 1. All paths are package-relative POSIX paths.
 * @typedef {{family:string,id:string,sourceDirectory:string,resourceType:{path:string,export:string},outputPattern:string,templates?:Record<string,string[]>,arrays?:Record<string,number>,plurals?:Record<string,{tokens:string[]}>}} ResourceFamily
 * @typedef {{schemaVersion:1,locales:string[],pluralLocaleAliases?:Record<string,string>,families:ResourceFamily[]}} ResourceConfig
 * @typedef {{schemaVersion:1,resources:readonly {id:string,path:string,locales:readonly string[]}[]}} LocalizationInventory
 * @typedef {ResourceFamily & {catalogs:Record<string,object>,pluralLocales:Record<string,string>}} ValidatedFamily
 */
function object(value, description) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error(`${description} must be an object`);
  return value;
}
function exactKeys(value, allowed, description) {
  object(value, description);
  for (const key of Object.keys(value)) if (!allowed.includes(key)) throw new Error(`${description}: unknown property ${key}`);
}
function boundedPath(root, relative) {
  if (typeof relative !== 'string' || !relative || relative.includes('\\') || relative.includes(':') || relative.includes('\0') || path.posix.isAbsolute(relative) || relative.split('/').some(part => !part || part === '.' || part === '..')) {
    throw new Error(`Expected bounded package-relative POSIX path: ${relative}`);
  }
  const absolute = path.join(root, ...relative.split('/'));
  // Refuse symlink escapes even when an output directory does not yet exist.
  let ancestor = absolute;
  while (!fs.existsSync(ancestor)) ancestor = path.dirname(ancestor);
  const realRoot = fs.realpathSync(root);
  const realAncestor = fs.realpathSync(ancestor);
  if (realAncestor !== realRoot && !realAncestor.startsWith(realRoot + path.sep)) throw new Error(`Path escapes bounded package root: ${relative}`);
  return absolute;
}
function boundedOutputPath(root, relative) {
  const absolute = boundedPath(root, relative);
  // Inspect directory entries themselves: existsSync follows dangling symlinks and
  // reports them as absent, allowing a later write to create their destination.
  let current = root;
  for (const component of relative.split('/')) {
    current = path.join(current, component);
    const entry = fs.lstatSync(current, { throwIfNoEntry: false });
    if (entry?.isSymbolicLink()) throw new Error(`Output symlinks are not allowed: ${relative}`);
  }
  return absolute;
}
function readJson(root, relative) {
  const file = boundedPath(root, relative);
  try { return JSON.parse(fs.readFileSync(file, 'utf8')); }
  catch (error) { throw new Error(`${relative}: ${error.message}`); }
}
function stringList(value, description) {
  if (!Array.isArray(value) || value.some(entry => typeof entry !== 'string' || !entry)) throw new Error(`${description} must be a string array`);
  if (new Set(value).size !== value.length) throw new Error(`Duplicate values in ${description}`);
}
function validateRules(family) {
  for (const name of ['templates', 'arrays', 'plurals']) {
    if (family[name] === undefined) continue;
    object(family[name], `${family.id}.${name}`);
    for (const [field, rule] of Object.entries(family[name])) {
      if (!/^[A-Za-z][A-Za-z0-9]*(\.[A-Za-z][A-Za-z0-9]*)*$/.test(field)) throw new Error(`${family.id}.${name}: invalid field path ${field}`);
      if (name === 'arrays') {
        if (!Number.isSafeInteger(rule) || rule < 1) throw new Error(`${family.id}.${field}: array length must be a positive integer`);
      } else {
        if (name === 'plurals') exactKeys(rule, ['tokens'], `${family.id}.${field}`);
        const tokens = name === 'plurals' ? rule.tokens : rule;
        stringList(tokens, `${family.id}.${field} tokens`);
        if (tokens.some(token => !/^(?:[A-Za-z][A-Za-z0-9]*|[0-9]+)$/.test(token))) throw new Error(`${family.id}.${field}: invalid token name`);
      }
    }
  }
}
function readConfig(packageRoot) {
  const root = path.resolve(packageRoot);
  const config = readJson(root, 'localization/resources.config.json');
  exactKeys(config, ['schemaVersion', 'locales', 'pluralLocaleAliases', 'families'], 'Resource config');
  if (config.schemaVersion !== 1) throw new Error('Resource config schemaVersion must be 1');
  stringList(config.locales, 'Resource locales');
  if (!config.locales.includes('en-US')) throw new Error('Resource locales must include en-US');
  for (const locale of config.locales) {
    if (!/^[a-z]{2,3}(?:-[A-Z][a-z]{3})?-[A-Z]{2}$/.test(locale)) throw new Error(`Resource locale must use its canonical culture name: ${locale}`);
  }
  const aliases = config.pluralLocaleAliases ?? {};
  object(aliases, 'pluralLocaleAliases');
  for (const [locale, alias] of Object.entries(aliases)) {
    if (!config.locales.includes(locale) || typeof alias !== 'string') throw new Error(`Invalid plural locale alias ${locale}`);
  }
  for (const locale of config.locales) {
    const pluralLocale = aliases[locale] ?? locale;
    let supported = false;
    try { supported = Intl.PluralRules.supportedLocalesOf([pluralLocale], { localeMatcher: 'lookup' }).length === 1; }
    catch { /* Unsupported tags receive the same actionable diagnostic. */ }
    if (!supported) throw new Error(`Resource culture ${locale}: ICU does not support plural locale ${pluralLocale}; an audited pluralLocaleAliases entry is required`);
  }
  if (!Array.isArray(config.families) || !config.families.length) throw new Error('Resource families must be a nonempty array');
  const ids = new Set(); const families = new Set(); const outputs = new Set();
  for (const family of config.families) {
    exactKeys(family, ['family', 'id', 'sourceDirectory', 'resourceType', 'outputPattern', 'templates', 'arrays', 'plurals'], 'Resource family');
    if (typeof family.id !== 'string' || !/^ApveeSpfxReactToolkit[A-Za-z0-9]+Strings$/.test(family.id)) throw new Error('Invalid resource ID');
    if (ids.has(family.id)) throw new Error(`Duplicate resource ID: ${family.id}`); ids.add(family.id);
    if (typeof family.family !== 'string' || !/^[a-z]+(?:-[a-z]+)*$/.test(family.family)) throw new Error(`${family.id}: invalid family name`);
    if (families.has(family.family)) throw new Error(`Duplicate family: ${family.family}`); families.add(family.family);
    boundedPath(root, family.sourceDirectory);
    exactKeys(family.resourceType, ['path', 'export'], `${family.id}.resourceType`);
    boundedPath(root, family.resourceType.path);
    if (!family.resourceType.path.endsWith('.ts') || typeof family.resourceType.export !== 'string' || !/^[A-Za-z][A-Za-z0-9]*$/.test(family.resourceType.export)) throw new Error(`${family.id}: invalid resource type reference`);
    if (typeof family.outputPattern !== 'string' || (family.outputPattern.match(/\{locale\}/g) ?? []).length !== 1) throw new Error(`${family.id}: output pattern requires exactly one {locale} token`);
    boundedPath(root, family.outputPattern);
    if (family.outputPattern !== `lib/controls/${family.family}/loc/{locale}.js`) throw new Error(`${family.id}: output must be the managed lib/controls/${family.family}/loc/{locale}.js path`);
    if (outputs.has(family.outputPattern)) throw new Error(`Duplicate output path: ${family.outputPattern}`); outputs.add(family.outputPattern);
    validateRules(family);
  }
  return { root, config };
}
/** Build metadata only; source catalogs and compiled lib are not required. @returns {LocalizationInventory} */
function buildInventory(packageRoot) {
  const { config } = readConfig(packageRoot);
  return { schemaVersion: 1, resources: [...config.families].sort((a, b) => compare(a.id, b.id)).map(family => ({ id: family.id, path: family.outputPattern, locales: [...config.locales].sort(compare) })) };
}
function fieldValue(resource, field, context) {
  let current = resource;
  for (const key of field.split('.')) {
    if (!current || typeof current !== 'object' || !Object.hasOwn(current, key)) throw new Error(`${context}.${field}: missing field`);
    current = current[key];
  }
  return current;
}
function tokens(value, required, context) {
  if (typeof value !== 'string') throw new Error(`${context}: template must be a string`);
  const actual = [...value.matchAll(/\{([^{}]*)\}/g)].map(match => match[1]);
  const remainder = value.replace(/\{[^{}]*\}/g, '');
  if (/[{}]/.test(remainder) || actual.length !== required.length || required.some(token => actual.filter(value => value === token).length !== 1) || actual.some(token => !required.includes(token))) {
    throw new Error(`${context}: expected exactly one of each token (${required.join(', ')}), received (${actual.join(', ')})`);
  }
}
function validateContent(value, context) {
  if (typeof value === 'string') { if (!value.trim()) throw new Error(`${context}: required label must be nonblank`); return; }
  if (Array.isArray(value)) { value.forEach((entry, index) => validateContent(entry, `${context}[${index}]`)); return; }
  if (value && typeof value === 'object') {
    for (const [key, entry] of Object.entries(value)) {
      if (['__locale', '__proto__', 'prototype', 'constructor'].includes(key)) throw new Error(`${context}: reserved property ${key}`);
      validateContent(entry, `${context}.${key}`);
    }
  }
  // TypeScript validates non-string scalars against the actual family contract.
}
function checkTypes(root, families) {
  const virtual = new Map();
  let index = 0;
  for (const family of families) {
    const contract = boundedPath(root, family.resourceType.path);
    if (!fs.existsSync(contract)) throw new Error(`${family.id}: missing resource type ${family.resourceType.path}`);
    for (const [locale, catalog] of Object.entries(family.catalogs)) {
      const filename = path.join(root, `__localization_validation_${index++}.ts`);
      const relativeImport = './' + family.resourceType.path.replace(/\.ts$/, '');
      virtual.set(filename, `import type { ${family.resourceType.export} } from ${JSON.stringify(relativeImport)};\nconst resource: ${family.resourceType.export} = ${JSON.stringify(catalog, undefined, 2)};\n`);
      family.validationFiles ??= {};
      family.validationFiles[filename] = locale;
    }
  }
  const options = { noEmit: true, strict: true, skipLibCheck: true, types: [], target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS, moduleResolution: ts.ModuleResolutionKind.Node10 };
  const host = ts.createCompilerHost(options);
  const read = host.readFile.bind(host); const exists = host.fileExists.bind(host);
  host.readFile = filename => virtual.get(filename) ?? read(filename);
  host.fileExists = filename => virtual.has(filename) || exists(filename);
  const program = ts.createProgram([...virtual.keys()], options, host);
  const diagnostics = ts.getPreEmitDiagnostics(program);
  if (diagnostics.length) throw new Error(diagnostics.map(diagnostic => {
    const family = families.find(entry => Object.hasOwn(entry.validationFiles, diagnostic.file?.fileName ?? ''));
    const context = family ? `${family.id}/${family.validationFiles[diagnostic.file.fileName]}` : diagnostic.file?.fileName ?? 'resource contract';
    return `${context}: ${ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n')}`;
  }).join('\n'));
  for (const family of families) delete family.validationFiles;
}
/** Validate every source before returning catalogs; no file is written. @returns {ValidatedFamily[]} */
function validateResources(packageRoot) {
  const { root, config } = readConfig(packageRoot);
  const results = [];
  for (const family of [...config.families].sort((a, b) => compare(a.id, b.id))) {
    const source = boundedPath(root, family.sourceDirectory);
    if (!fs.existsSync(source)) throw new Error(`${family.id}: missing resource directory ${family.sourceDirectory}`);
    const expected = config.locales.map(locale => `${locale}.json`).sort(compare);
    const actual = fs.readdirSync(source).sort(compare);
    if (expected.join('\n') !== actual.join('\n')) throw new Error(`${family.id}: catalog cultures differ; missing: ${expected.filter(file => !actual.includes(file)).join(', ')}; extra: ${actual.filter(file => !expected.includes(file)).join(', ')}`);
    const catalogs = {}; const pluralLocales = {};
    for (const locale of [...config.locales].sort(compare)) {
      const context = `${family.id}/${locale}`;
      const catalog = readJson(root, `${family.sourceDirectory}/${locale}.json`);
      object(catalog, context); validateContent(catalog, context);
      for (const [field, required] of Object.entries(family.templates ?? {})) tokens(fieldValue(catalog, field, context), required, `${context}.${field}`);
      for (const [field, length] of Object.entries(family.arrays ?? {})) {
        const value = fieldValue(catalog, field, context);
        if (!Array.isArray(value) || value.length !== length) throw new Error(`${context}.${field}: expected array of ${length} elements`);
      }
      const pluralLocale = config.pluralLocaleAliases?.[locale] ?? locale;
      for (const [field, rule] of Object.entries(family.plurals ?? {})) {
        const branches = object(fieldValue(catalog, field, context), `${context}.${field}`);
        const categories = new Intl.PluralRules(pluralLocale).resolvedOptions().pluralCategories.sort(compare);
        if (Object.keys(branches).sort(compare).join(',') !== categories.join(',')) throw new Error(`${context}.${field}: plural branches must be exactly ${categories.join(', ')}; received ${Object.keys(branches).join(', ')}`);
        for (const [branch, template] of Object.entries(branches)) tokens(template, rule.tokens, `${context}.${field}.${branch}`);
      }
      catalogs[locale] = catalog; pluralLocales[locale] = pluralLocale;
    }
    results.push({ ...family, catalogs, pluralLocales });
  }
  checkTypes(root, results);
  return results;
}
function stable(value) {
  if (Array.isArray(value)) return value.map(stable);
  if (value && typeof value === 'object') return Object.fromEntries(Object.keys(value).sort(compare).map(key => [key, stable(value[key])]));
  return value;
}
function serialize(value) { return JSON.stringify(value, undefined, 2).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029'); }
/** Emit data-only native resources; validate all inputs and output paths before mutation. */
function emitLocalizedResources(packageRoot) {
  const root = path.resolve(packageRoot); const families = validateResources(root);
  const writes = []; const removals = [];
  for (const family of families) {
    const wanted = new Set();
    for (const [locale, catalog] of Object.entries(family.catalogs)) {
      const target = boundedOutputPath(root, family.outputPattern.replace('{locale}', locale.toLowerCase()));
      wanted.add(target);
      writes.push([target, `${generatedMarker}define([], function () {\n  return ${serialize(stable({ ...catalog, __locale: family.pluralLocales[locale] }))};\n});\n`]);
    }
    const directory = path.dirname(boundedOutputPath(root, family.outputPattern));
    if (fs.existsSync(directory)) for (const file of fs.readdirSync(directory)) {
      const target = boundedOutputPath(root, path.posix.join(path.posix.dirname(family.outputPattern), file));
      if (!wanted.has(target) && /^[a-z]{2,3}(?:-[a-z]{4})?-[a-z]{2}\.js$/.test(file) && fs.lstatSync(target).isFile() && fs.readFileSync(target, 'utf8').startsWith(generatedMarker)) removals.push(target);
    }
  }
  for (const [target, content] of writes) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) fs.writeFileSync(target, content);
  }
  for (const file of removals) fs.unlinkSync(file);
}
function main(args) {
  const modes = ['--write-inventory', '--check-inventory', '--emit'];
  const mode = args.shift();
  if (!modes.includes(mode)) throw new Error(`Expected one mode: ${modes.join(', ')}`);
  let packageRoot = path.resolve(__dirname, '../packages/spfx-react-toolkit');
  if (args.length) {
    if (args.length !== 2 || args[0] !== '--package-root' || !args[1]) throw new Error('Unknown options; optional --package-root <directory> is supported');
    packageRoot = path.resolve(args[1]);
  }
  if (mode === '--emit') { emitLocalizedResources(packageRoot); return; }
  const bytes = JSON.stringify(buildInventory(packageRoot), undefined, 2) + '\n';
  const inventory = boundedOutputPath(packageRoot, 'localization/resources.json');
  if (mode === '--check-inventory') {
    if (!fs.existsSync(inventory) || fs.readFileSync(inventory, 'utf8') !== bytes) throw new Error('Localization inventory is stale; run scripts/localization-resources.cjs --write-inventory');
    return;
  }
  fs.writeFileSync(inventory, bytes);
}
module.exports = { buildInventory, validateResources, emitLocalizedResources };
if (require.main === module) {
  try { main(process.argv.slice(2)); }
  catch (error) { process.stderr.write(`${error.message}\n`); process.exitCode = 1; }
}
