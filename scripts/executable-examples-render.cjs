/**
 * Render accepted canonical entries without reading files or evaluating snippets.
 * Families and features sort deterministically; scenarios keep their input order
 * within a feature. Callers restore canonical source-example order after collection.
 * Extracted source bytes are copied unchanged after the ownership marker.
 * @param {ExecutableExample[]} examples Accepted entries in canonical source order.
 * @returns {ArtifactSet} Generated modules and their lazy catalogue.
 */
function renderExecutableExamples(examples) {
  const groups = new Map();
  const ids = new Set();
  const identities = new Set();
  for (const example of examples) {
    if (!/^[a-f0-9]{64}$/.test(example.id)) throw new Error(`Invalid executable example identity: ${example.id}.`);
    const identity = JSON.stringify([example.ownerKey, example.title]);
    if (ids.has(example.id) || identities.has(identity)) throw new Error(`Executable example destination collision: ${example.ownerKey} / ${example.title}.`);
    ids.add(example.id);
    identities.add(identity);
    if (!groups.has(example.groupKey)) groups.set(example.groupKey, new Map());
    const features = groups.get(example.groupKey);
    if (!features.has(example.featureKey)) features.set(example.featureKey, { key: example.featureKey, title: example.featureTitle, examples: [] });
    features.get(example.featureKey).examples.push(example);
  }
  const orderedGroups = [...groups].sort(([a], [b]) => compare(a, b)).map(([key, features]) => ({
    key, title: Object.hasOwn(familyLabels, key) ? familyLabels[key] : key,
    features: [...features.values()].sort((a, b) => compare(a.title, b.title) || compare(a.key, b.key)),
  }));
  const ordered = orderedGroups.flatMap(group => group.features.flatMap(feature => feature.examples));
  const artifacts = {};
  const entries = [];
  const indices = new Map();
  for (const [index, example] of ordered.entries()) {
    const { id, ownerKey, title, groupRoute, groupKey, featureKey, featureTitle, publicNames, source, metadata } = example;
    artifacts[`${executableRoot}/${id}.tsx`] = ownership + '\n' + example.code;
    indices.set(id, index);
    const data = JSON.stringify({ id, ownerKey, title, groupRoute, groupKey, featureKey, featureTitle, publicNames, source, metadata }, undefined, 2);
    const load = `import(/* webpackChunkName: 'spfx-jsdoc-${id}' */ "./${id}")`;
    const nativeLoad = `${load}.then(module => {
    type Source = NativeSourceProperties<NonNullable<Parameters<typeof module.Demo>[0]['propertyPane']>>;
    // Prove every concrete source key/domain/optionality before common loader erasure.
    const CheckedDemo: NativeCompatible<ISpFxReactToolkitTestWebPartProps, Source> extends true ? typeof module.Demo : never = module.Demo;
    return { Demo: (props: ExecutableExampleProps): React.ReactElement => CheckedDemo(props) };
  })`;
    entries.push(data.slice(0, -2) + `,\n  load: () => ${metadata.hostAdapter === 'propertyPane' ? nativeLoad : load}\n}`);
  }
  const hierarchy = orderedGroups.map(group => {
    const features = group.features.map(feature => `    { key: ${JSON.stringify(feature.key)}, title: ${JSON.stringify(feature.title)}, scenarios: [${feature.examples.map(example => `executableExamples[${indices.get(example.id)}]`).join(', ')}] }`);
    return `  { key: ${JSON.stringify(group.key)}, title: ${JSON.stringify(group.title)}, features: [\n${features.join(',\n')}\n  ] }`;
  });
  const native = examples.some(example => example.metadata.hostAdapter === 'propertyPane');
  const types = native ? catalogueTypes.replace('  shell?: ExecutableShellPort;',
    '  shell?: ExecutableShellPort;\n  propertyPane?: DemoPropertyPanePort<ISpFxReactToolkitTestWebPartProps>;') : catalogueTypes;
  artifacts[executableRoot + '/catalogue.ts'] = ownership + '\n' + (native ? nativeTypes : '') + types +
    `\nexport const executableExamples: readonly ExecutableExampleEntry[] = [${entries.length ? '\n' + entries.join(',\n') + '\n' : ''}];\n` +
    `\nexport const executableGroups: readonly ExecutableGroup[] = [${hierarchy.length ? '\n' + hierarchy.join(',\n') + '\n' : ''}];\n`;
  return Object.fromEntries(Object.keys(artifacts).sort(compare).map(route => [route, artifacts[route]]));
}
module.exports = { renderExecutableExamples, executableRoot, ownership };
