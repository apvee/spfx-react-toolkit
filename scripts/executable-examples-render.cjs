const executableRoot = 'apps/spfx-react-toolkit-test/src/webparts/spFxReactToolkitTest/components/generated/jsdoc-examples';
const ownership = '// Generated by scripts/executable-examples.cjs. Do not edit.';
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0;
const familyLabels = { controls: 'Controlli', hooks: 'Hook', core: 'Provider e contesto', helpers: 'Helper e stili', services: 'Servizi', 'property-pane': 'Property Pane' };
const nativeTypes = `import type { ISpFxReactToolkitTestWebPartProps } from '../../../SpFxReactToolkitTestWebPart';
import type { DemoPropertyPanePort } from '../../shared/NativePropertyPaneDemoHost';

type NativeSourceProperties<T> = T extends DemoPropertyPanePort<infer P> ? P : never;
type NativeAny<T> = 0 extends (1 & T) ? true : false;
type NativeUnsafe<T> = NativeAny<T> extends true ? true : unknown extends T ? true :
  T extends readonly (infer V)[] ? NativeUnsafe<V> :
  T extends object ? true extends { [K in keyof T]-?: NativeUnsafe<T[K]> }[keyof T] ? true : false : false;
type NativeEqual<A, B> = true extends NativeUnsafe<A> | NativeUnsafe<B> ? false :
  [A] extends [B] ? [B] extends [A] ? true : false : false;
type NativeOptional<T, K extends keyof T> = {} extends Pick<T, K> ? true : false;
type NativeDomainMismatch<H, S> = S extends object ? { [K in keyof S]-?: K extends keyof H ?
  NativeEqual<H[K], S[K]> extends true ? NativeEqual<NativeOptional<H, K>, NativeOptional<S, K>> extends true ? never : K : K : K
}[keyof S] : never;
type NativeCompatible<H, S> = [NativeDomainMismatch<H, S>] extends [never] ? true : false;
`;
