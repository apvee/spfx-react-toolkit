/** Full path set, exact SHA-256 per file and a length-framed path/byte digest.
 * @param {import('./documentation-artifacts.cjs').ArtifactSet} artifacts Expected or disk-read bytes.
 * @returns {{paths: string[], perFile: Record<string,string>, digest: string}} Exact byte identity.
 */
function hashArtifacts(artifacts) {
  const paths = Object.keys(artifacts).sort(compare);
  const perFile = {};
  const digest = crypto.createHash('sha256');
  for (const route of paths) {
    const name = Buffer.from(route, 'utf8');
    const bytes = Buffer.isBuffer(artifacts[route]) ? artifacts[route] : Buffer.from(artifacts[route], 'utf8');
    const length = Buffer.alloc(8);
    length.writeBigUInt64BE(BigInt(name.length)); digest.update(length); digest.update(name);
    length.writeBigUInt64BE(BigInt(bytes.length)); digest.update(length); digest.update(bytes);
    perFile[route] = crypto.createHash('sha256').update(bytes).digest('hex');
  }
  return { paths, perFile, digest: digest.digest('hex') };
}
const diskArtifacts = (root, routes) => Object.fromEntries(routes.map(route => [route, fs.readFileSync(path.join(root, route))]));
function directoryArtifacts(root, directory) {
  const routes = [];
  function walk(route) {
    for (const entry of fs.readdirSync(path.join(root, route), { withFileTypes: true })) {
      const child = path.posix.join(route, entry.name);
      if (entry.isDirectory()) walk(child);
      else { assert.ok(entry.isFile(), `Rebuilt output is not an ordinary file: ${child}.`); routes.push(child); }
    }
  }
  walk(directory);
  return diskArtifacts(root, routes);
}
