/** Copy only real versionable inputs; no Git inventory, outputs or evidence. */
function copyInputs(root, source, mirror, config, reverse) {
  const inputs = new Map();
  const directories = new Set();
  function add(base, route) {
    if (excluded(route) || route === path.posix.join(config.packageRoot, 'README.md')) return;
    const filename = path.join(base, route);
    if (!fs.existsSync(filename)) return;
    const stat = fs.lstatSync(filename);
    if (stat.isSymbolicLink()) throw new Error(`Cold input must not be a symlink: ${route}.`);
    if (stat.isDirectory()) {
      directories.add(route);
      for (const entry of fs.readdirSync(filename).sort(compare)) add(base, path.posix.join(route, entry));
    } else if (stat.isFile()) inputs.set(route, filename);
    else throw new Error(`Cold input is not an ordinary file: ${route}.`);
  }
  for (const route of ['README.md', 'AGENTS.md', 'LICENSE', 'package.json', 'package-lock.json']) add(source, route);
  // Fixture inputs intentionally have no workspace lock or executable engine.
  for (const route of ['package.json', 'package-lock.json']) if (!inputs.has(route)) add(root, route);
  // This finite executable closure belongs to the docs engine. Editorial links
  // below may admit individual tooling files as data, never entire tool trees.
  const engineFiles = [
    'documentation-artifacts.cjs',
    'documentation-context.cjs',
    'documentation-contract.cjs',
    'documentation-examples.cjs',
    'documentation-guides.cjs',
    'documentation-inputs.cjs',
    'documentation-markdown.cjs',
    'documentation-model.cjs',
    'documentation-render.cjs',
    'documentation-tsdoc.cjs',
    'documentation.cjs',
    'documentation.config.cjs',
    'executable-examples-model.cjs',
    'executable-examples-render.cjs',
    'executable-examples.cjs',
    'generated-artifacts.cjs',
    'generated.cjs',
    'public-surface.helpers.cjs',
    'verify-documentation-reproducibility.cjs',
    'verify-public-docs.cjs',
  ];
  for (const entry of engineFiles) {
    const route = 'scripts/docs/' + entry;
    if (!fs.existsSync(path.join(root, route))) throw new Error(`Missing cold documentation engine input: ${route}.`);
    add(root, route);
  }
  add(root, probes);
  add(source, config.sourceRoot);
  for (const name of ['package.json', 'tsconfig.json', 'tsdoc.json', 'THIRD-PARTY-NOTICES.md', 'localization/resources.json']) add(source, path.posix.join(config.packageRoot, name));
  // The parser's project tag contract is part of the copied executable closure.
  if (!inputs.has('packages/spfx-react-toolkit/tsdoc.json')) add(root, 'packages/spfx-react-toolkit/tsdoc.json');
  add(source, 'docs');
  const { markdownLinks, externalTarget } = require('./documentation-markdown.cjs');
  // Derive actual manual/editorial/README target closure with the existing parser.
  function addLinkTargets(route, content) {
    for (const href of markdownLinks(content)) {
      if (externalTarget(href)) continue;
      const target = decodeURIComponent(href.split('#')[0].split('?')[0]);
      if (!target) continue;
      const local = path.posix.normalize(target.startsWith('/') ? target.slice(1) : path.posix.join(path.posix.dirname(route), target));
      if (local.startsWith('../')) throw new Error(`Cold input link escapes root: ${route}: ${href}.`);
      if (excluded(local) || local === path.posix.join(config.packageRoot, 'README.md')) continue;
      const absolute = path.join(source, local);
      if (fs.existsSync(absolute) && fs.lstatSync(absolute).isDirectory()) directories.add(local);
      else add(source, local);
    }
  }
  // The published README preserves some package-relative targets. Derive them
  // from the root owner through the real renderer; never read/copy old output.
  const { renderPackageReadme } = require('./documentation-render.cjs');
  addLinkTargets(path.posix.join(config.packageRoot, 'README.md'), renderPackageReadme(fs.readFileSync(inputs.get('README.md'), 'utf8'), config));
  for (const [route, filename] of inputs) if (route.endsWith('.md')) addLinkTargets(route, fs.readFileSync(filename, 'utf8'));
  for (const directory of [...directories].sort(compare)) fs.mkdirSync(path.join(mirror, directory), { recursive: true });
  const routes = [...inputs.keys()].sort(compare);
  if (reverse) routes.reverse();
  const stamp = new Date(reverse ? '2001-02-03T04:05:06Z' : '2020-03-04T05:06:07Z');
  for (const route of routes) {
    const destination = path.join(mirror, route);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.copyFileSync(inputs.get(route), destination);
    fs.utimesSync(destination, stamp, stamp);
  }
  fs.symlinkSync(fs.realpathSync(path.join(root, 'node_modules')), path.join(mirror, 'node_modules'), 'dir');
  return routes;
}
function childProcess(mirror, neutral, config, environment, extra = []) {
  const directory = path.join(mirror, probes);
  const args = ['--require', path.join(directory, 'offline-guard.cjs'), '--require', path.join(directory, 'read-audit.cjs')];
  if (environment.reverse) args.push('--require', path.join(directory, 'discovery-order.cjs'));
  args.push(path.join(mirror, 'scripts/docs/verify-documentation-reproducibility.cjs'), '--child', JSON.stringify(config), ...extra);
  const child = spawnSync(process.execPath, args, { cwd: environment.reverse ? neutral : mirror, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024,
    env: { ...process.env, NODE_PATH: '', NODE_OPTIONS: '', TOOLKIT_DOCS_MODE: 'write', LANG: environment.locale, LC_ALL: environment.locale, TZ: environment.tz } });
  assert.equal(child.status, 0, `Copied documentation child failed (${environment.locale}/${environment.tz}):\n${child.stderr}\n${child.stdout}`);
  return JSON.parse(child.stdout);
}
function mutatePublicComment(mirror, target) {
  assert.ok(target, 'Generated public API source link supplies a JSDoc mutation target.');
  const filename = path.join(mirror, target.file);
  const source = fs.readFileSync(filename, 'utf8');
  const offset = source.split('\n').slice(0, target.line - 1).join('\n').length;
  const start = source.lastIndexOf('/**', offset);
  const end = source.indexOf('*/', start);
  assert.ok(start >= 0 && end >= start && end <= offset + 3, 'Public source declaration has preceding JSDoc.');
  const comment = source.slice(start, end);
  const changed = comment.replace(/^(\s*\* )(?![@*\s])([^\n]+)$/m, '$1$2 Reproducibility source mutation.');
  assert.notEqual(changed, comment);
  fs.writeFileSync(filename, source.slice(0, start) + changed + source.slice(end));
}

function addExecutableProbe(mirror, target) {
  const filename = path.join(mirror, target.file);
  const source = fs.readFileSync(filename, 'utf8');
  const offset = source.split('\n').slice(0, target.line - 1).join('\n').length;
  const start = source.lastIndexOf('/**', offset);
  const end = source.indexOf('*/', start);
  assert.ok(start >= 0 && end >= start && end <= offset + 3, 'Public source declaration has preceding JSDoc.');
  const insertion = source.lastIndexOf('\n', end) + 1;
  assert.match(source.slice(insertion, end), /^[ \t]+$/, 'Owning JSDoc closes on a separate line.');
  const margin = source.slice(insertion, end);
  const scenario = [
    '@scenario Reproducibility executable',
    '```tsx', "import * as React from 'react';",
    "export function Demo(): React.ReactElement { return React.createElement('div', undefined, 'Cold executable original'); }",
    "export const demo = { host: 'none', kind: 'snapshot', contentPlacement: 'subject', observe: 'Cold executable is visible.' };",
    '```',
  ].map(line => margin + '* ' + line + '\n').join('');
  fs.writeFileSync(filename, source.slice(0, insertion) + scenario + source.slice(insertion));
}

/** Two copied cold engines, real write/rebuild and fresh locale/timezone probes.
 * The outer verifier alone reads original expected outputs after reconstruction.
 * @param {string} root Installation/checkout root.
 * @param {import('./documentation-model.cjs').Config & {fixtureRoot?: string}} [config] Versioned project configuration; fixtureRoot is test-only input selection.
 * @returns {{ok: boolean, hashes: object, environments: object[], audit: object, sourceMutationChanged: boolean, developmentSourceMutationChanged: boolean, developmentRebuild: object, offlineProbes: number}} Proof evidence; throws on any mismatch.
 */
function verifyReproducibility(root, config = defaultConfig) {
  root = fs.realpathSync(root);
  const source = config.fixtureRoot || root;
  const { fixtureRoot, ...project } = config;
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'documentation-reproducibility-'));
  try {
    const mirrors = ['cold-a', 'cold-b'].map(name => { const directory = path.join(temporary, name); fs.mkdirSync(directory); return directory; });
    const copied = mirrors.map((mirror, index) => copyInputs(root, source, mirror, project, Boolean(index)));
    assert.deepEqual([...copied[0]].sort(compare), [...copied[1]].sort(compare));
    for (const mirror of mirrors) for (const route of ['.git', '.docs', 'lib', project.packageRoot + '/lib', 'docs/api', 'docs/guides', 'docs/getting-started', 'docs/development', 'docs/INDEX.md', 'llms.txt', project.packageRoot + '/README.md', executableRoot]) assert.equal(fs.existsSync(path.join(mirror, route)), false, `Cold mirror contains excluded input: ${route}.`);
    const developmentSources = copied[0].filter(route => route.startsWith('docs/_sources/development/'));
    assert.ok(developmentSources.length > 0, 'Cold reconstruction requires maintained development sources.');
    const developmentInputHashes = hashArtifacts(diskArtifacts(mirrors[0], developmentSources));
    const environments = [{ locale: 'C', tz: 'UTC', reverse: false }, { locale: 'C', tz: 'Europe/Rome', reverse: true },
      { locale: 'it_IT.UTF-8', tz: 'UTC', reverse: true }, { locale: 'it_IT.UTF-8', tz: 'Europe/Rome', reverse: false }];
    let baseline;
    let mutationTarget;
    let familyHashes;
    const evidence = [];
    for (const [index, environment] of environments.entries()) {
      const result = childProcess(mirrors[index % 2], temporary, project, environment, mirrors);
      if (!baseline) { baseline = result.hashes; mutationTarget = result.mutationTarget; familyHashes = result.families; }
      assert.deepEqual(result.families, familyHashes, 'Each generated family must be reproducible.');
      assert.deepEqual(result.hashes, baseline, 'Fresh locale/timezone/discovery reconstruction differs.');
      assert.deepEqual(result.diskHashes, baseline, 'Actual written bytes differ from the virtual ArtifactSet.');
      assert.equal(result.environment.timezone, environment.tz, 'Fresh timezone perturbation was ineffective.');
      if (environment.locale.startsWith('it_')) assert.match(result.environment.locale, /^it(?:-|$)/, 'Fresh locale perturbation was ineffective.');
      evidence.push({ ...environment, observed: result.environment, audit: result.audit });
    }
    assert.equal(new Set(evidence.map(item => item.observed.locale)).size, 2, 'Both requested locales must be effective.');
    for (const start of [0, 2]) assert.notEqual(evidence[start].observed.fixedInstant, evidence[start + 1].observed.fixedInstant, 'Timezone variation must change a fixed instant rendering within each locale.');
    // Read previous outputs only here, outside all cold generation processes.
    if (!fixtureRoot) {
      assert.deepEqual(hashArtifacts(diskArtifacts(root, baseline.paths)), baseline, 'Checkout outputs differ from cold reconstruction.');
      const expected = Object.fromEntries(Object.entries(diskArtifacts(mirrors[1], baseline.paths)).map(([route, bytes]) => [route, bytes.toString('utf8')]));
      assert.deepEqual(require('./generated-artifacts.cjs').compareGeneratedArtifacts(root, Object.fromEntries(familyHashes.documentation.paths.map(route => [route, expected[route]])), require('./documentation-artifacts.cjs').documentationPolicy(project)), { missing: [], changed: [], orphan: [] }, 'Checkout documentation set differs from cold reconstruction.');
      assert.deepEqual(require('./generated-artifacts.cjs').compareGeneratedArtifacts(root, Object.fromEntries(familyHashes.examples.paths.map(route => [route, expected[route]])), require('./executable-examples.cjs').executableExamplesPolicy(project)), { missing: [], changed: [], orphan: [] }, 'Checkout executable set differs from cold reconstruction.');
    }
    const manual = path.join(mirrors[0], 'docs/api/manual-stranger.md');
    const orphan = path.join(mirrors[0], 'docs/api/stale-owned.md');
    fs.writeFileSync(manual, '# Manual stranger\n\nPreserve these bytes.\n');
    fs.utimesSync(manual, new Date('2000-01-01Z'), new Date('2000-01-01Z'));
    const executableManual = path.join(mirrors[0], executableRoot, 'manual.ts');
    const executableOrphan = path.join(mirrors[0], executableRoot, 'orphan.ts');
    fs.writeFileSync(executableManual, '// Manual executable stranger\n');
    fs.utimesSync(executableManual, new Date('2000-01-01Z'), new Date('2000-01-01Z'));
    const manualExecutableBefore = { bytes: fs.readFileSync(executableManual), mtime: fs.statSync(executableManual).mtimeMs };
    fs.writeFileSync(executableOrphan, executableOwnership + '\nexport {};\n');
    const before = { bytes: fs.readFileSync(manual), mtime: fs.statSync(manual).mtimeMs };
    fs.writeFileSync(orphan, ownership + '\n\n# Stale\n');
    for (const route of baseline.paths) fs.unlinkSync(path.join(mirrors[0], route));
    const developmentDirectory = path.join(mirrors[0], 'docs/development');
    fs.rmSync(developmentDirectory, { recursive: true });
    assert.equal(fs.existsSync(developmentDirectory), false, 'The whole public development directory must be absent before rebuilding.');
    assert.deepEqual(hashArtifacts(diskArtifacts(mirrors[0], developmentSources)), developmentInputHashes, 'Deleting outputs must retain all maintained development source bytes.');
    const rebuilt = childProcess(mirrors[0], temporary, project, environments[0], mirrors);
    assert.deepEqual(rebuilt.hashes, baseline);
    assert.deepEqual(rebuilt.diskHashes, baseline);
    assert.equal(fs.existsSync(orphan), false);
    assert.equal(fs.existsSync(executableOrphan), false);
    assert.deepEqual(fs.readFileSync(executableManual), manualExecutableBefore.bytes);
    assert.equal(fs.statSync(executableManual).mtimeMs, manualExecutableBefore.mtime);
    assert.deepEqual(fs.readFileSync(manual), before.bytes);
    assert.equal(fs.statSync(manual).mtimeMs, before.mtime);
    const developmentRoutes = baseline.paths.filter(route => route.startsWith('docs/development/'));
    const developmentRebuild = { directoryAbsentBefore: true, sourcesRetained: true, hashes: hashArtifacts(directoryArtifacts(mirrors[0], 'docs/development')) };
    assert.deepEqual(developmentRebuild.hashes, hashArtifacts(diskArtifacts(mirrors[1], developmentRoutes)), 'The entire development path set and bytes must be reconstructed.');
    mutatePublicComment(mirrors[0], mutationTarget);
    const developmentMutation = { source: 'docs/_sources/development/INDEX.md', route: 'docs/development/INDEX.md' };
    assert.ok(copied[0].includes(developmentMutation.source), 'The development index must have a maintained source.');
    fs.appendFileSync(path.join(mirrors[0], developmentMutation.source), '\nReproducibility development source mutation.\n');
    addExecutableProbe(mirrors[0], mutationTarget);
    const mutated = childProcess(mirrors[0], temporary, project, environments[1], mirrors);
    assert.notEqual(mutated.hashes.digest, baseline.digest, 'Public JSDoc mutation must affect generated bytes.');
    assert.notEqual(mutated.hashes.perFile[mutationTarget.route], baseline.perFile[mutationTarget.route], 'Mutated owning API page must change.');
    assert.notEqual(mutated.hashes.perFile[developmentMutation.route], baseline.perFile[developmentMutation.route], 'Development source mutation must change its owning public page.');
    assert.deepEqual(mutated.diskHashes, mutated.hashes);
    assert.notEqual(mutated.families.examples.digest, familyHashes.examples.digest, 'Adding a source executable must change executable outputs.');
    const probeSource = path.join(mirrors[0], mutationTarget.file);
    fs.writeFileSync(probeSource, fs.readFileSync(probeSource, 'utf8').replace('Cold executable original', 'Cold executable changed'));
    const exampleMutated = childProcess(mirrors[0], temporary, project, environments[0], mirrors);
    assert.notEqual(exampleMutated.families.examples.digest, mutated.families.examples.digest, 'Scenario code must change executable outputs.');
    assert.deepEqual(exampleMutated.families.documentation, mutated.families.documentation, 'Scenario code without an explicit include must leave documentation unchanged.');
    assert.deepEqual(exampleMutated.diskHashes, exampleMutated.hashes);
    const probeNames = ['fetch', 'http', 'https', 'http2', 'net', 'net-prototype', 'tls', 'dgram', 'dns', 'dns-promises', 'child', 'worker'];
    for (const name of probeNames) {
      const child = spawnSync(process.execPath, ['--require', path.join(mirrors[1], probes, 'offline-guard.cjs'), path.join(mirrors[1], probes, 'offline-probe.cjs'), name], { encoding: 'utf8', env: { ...process.env, NODE_PATH: '', NODE_OPTIONS: '' }, cwd: temporary });
      assert.notEqual(child.status, 0, name);
      assert.match(child.stderr, /DOC_OFFLINE_FORBIDDEN/, name);
    }
    const escape = spawnSync(process.execPath, ['--require', path.join(mirrors[1], probes, 'offline-guard.cjs'), '--require', path.join(mirrors[1], probes, 'read-audit.cjs'), path.join(mirrors[1], probes, 'source-escape-probe.cjs'), root, JSON.stringify(baseline.paths)], { encoding: 'utf8', cwd: temporary, env: { ...process.env, NODE_PATH: '', NODE_OPTIONS: '' } });
    assert.equal(escape.status, 0, escape.stderr);
    return { ok: true, hashes: baseline, families: familyHashes, executableSourceMutationChanged: true, executableManualPreserved: true, executableOrphanRemoved: true, bytes: Object.values(diskArtifacts(mirrors[1], baseline.paths)).reduce((sum, bytes) => sum + bytes.length, 0), inputs: copied[0].length, copiedInputs: [...copied[0]].sort(compare), copiedInputHashes: hashArtifacts(diskArtifacts(mirrors[1], copied[1])),
      environments: evidence, audit: evidence[0].audit, sourceMutationChanged: true, developmentSourceMutationChanged: true, developmentRebuild, offlineProbes: probeNames.length, sourceEscape: JSON.parse(escape.stdout), platform: process.platform, node: process.version };
  } finally { fs.rmSync(temporary, { recursive: true, force: true }); }
}
function runChild(config, mirrorPaths) {
  const root = path.resolve(__dirname, '../..');
  const { generateAllArtifacts } = require('./generated.cjs');
  const { applyGeneratedArtifacts } = require('./generated-artifacts.cjs');
  const families = generateAllArtifacts(root, config);
  const artifacts = { ...families.documentation, ...families.examples };
  const mirrorSpellings = [...new Set([...mirrorPaths, ...mirrorPaths.map(mirror => fs.realpathSync(mirror))])];
  for (const text of Object.values(artifacts)) for (const mirror of mirrorSpellings) assert.equal(text.includes(mirror), false, 'Output leaks an absolute mirror path.');
  applyGeneratedArtifacts(root, families.documentation, 'write', require('./documentation-artifacts.cjs').documentationPolicy(config));
  applyGeneratedArtifacts(root, families.examples, 'write', require('./executable-examples.cjs').executableExamplesPolicy(config));
  let mutationTarget;
  for (const [route, text] of Object.entries(artifacts)) if (route.startsWith('docs/api/')) {
    const match = text.match(/\]\(https:\/\/[^\s)]+\/blob\/[^/]+\/([^\s)#]+)#L(\d+)\)/);
    if (match) { mutationTarget = { route, file: decodeURIComponent(match[1]), line: Number(match[2]) }; break; }
  }
  const audit = globalThis.__documentationReadAudit();
  process.stdout.write(JSON.stringify({ hashes: hashArtifacts(artifacts), families: Object.fromEntries(Object.entries(families).map(([family, expected]) => [family, hashArtifacts(expected)])), diskHashes: hashArtifacts(diskArtifacts(root, Object.keys(artifacts))), mutationTarget,
    environment: { locale: Intl.DateTimeFormat().resolvedOptions().locale, timezone: Intl.DateTimeFormat().resolvedOptions().timeZone, fixedInstant: new Date('2020-06-01T12:00:00Z').toString() },
    audit: { reads: audit.reads, packages: audit.packages, source: audit.files.filter(file => file.startsWith(path.join(root, config.sourceRoot))).length,
      scripts: audit.files.filter(file => file.startsWith(path.join(root, 'scripts'))).length, config: audit.files.includes(path.join(root, config.tsconfig)) } }));
}
if (require.main === module) {
  try {
    if (process.argv[2] === '--child') runChild(JSON.parse(process.argv[3]), process.argv.slice(4));
    else console.log(JSON.stringify(verifyReproducibility(path.resolve(__dirname, '../..')), undefined, 2));
  } catch (error) { console.error(error.stack || error); process.exitCode = 1; }
}
