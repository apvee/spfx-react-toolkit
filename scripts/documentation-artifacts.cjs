const fs = require('node:fs');
const path = require('node:path');
const defaultConfig = require('./documentation.config.cjs');
const { buildApiGraph } = require('./documentation-model.cjs');
const { getPageIntroductions, buildDocumentationModel, validateDocumentation, resolveDocumentationReference } = require('./documentation-contract.cjs');
const { checkDocumentationExamples } = require('./documentation-examples.cjs');
const { renderApiPages, renderCatalog, renderPackageReadme, renderLlms } = require('./documentation-render.cjs');
const { discoverEditorialSources, renderEditorialPages, collectPublicTargets, validatePublicLinks } = require('./documentation-guides.cjs');
const { markdownLabel, resolveMarkdown, transformMarkdown, externalTarget } = require('./documentation-markdown.cjs');

/** @typedef {import('./documentation-model.cjs').Config} Config */
/** @typedef {import('./documentation-model.cjs').Diagnostic} Diagnostic */
/** @typedef {import('./documentation-render.cjs').PublicPage} PublicPage */
/** @typedef {Record<string, string>} ArtifactSet Repository-relative POSIX paths to canonical UTF-8/LF text. */
/** @typedef {{missing: string[], changed: string[], orphan: string[]}} ArtifactDiff Sorted output differences. */
/** @typedef {{ok: boolean, mode: 'write'|'check', diff: ArtifactDiff}} ArtifactResult Write returns the applied diff; check returns freshness without mutation. */
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0;
const finish = text => text.replace(/\r\n?/g, '\n').replace(/\n*$/, '\n');
const ownership = '<!-- Generated by scripts/documentation.cjs. Do not edit. -->';
const directories = ['docs/api', 'docs/getting-started', 'docs/guides', 'docs/development'];
const packageReadme = config => path.posix.join(config.packageRoot, 'README.md');

function validRoute(route) {
  return typeof route === 'string' && route.length > 0 && !/[\\\0?#:]/.test(route) &&
    !path.posix.isAbsolute(route) && route.split('/').every(part => part && part !== '.' && part !== '..');
}
const privateRoute = route => /(?:^|\/)(?:\.docs|_sources|node_modules|\.git)(?:\/|$)/.test(route);
function allowed(route, config) {
  if (privateRoute(route)) return false;
  return route === 'llms.txt' || route === 'docs/INDEX.md' || route === packageReadme(config) ||
    directories.some(directory => route.startsWith(directory + '/') && route.endsWith('.md'));
}
/** Root aliases are permitted; symlinks below it are never output destinations. */
function checkedPath(root, route) {
  if (!validRoute(route)) throw new Error(`Invalid documentation path: ${route}.`);
  let current = root;
  const parts = route.split('/');
  for (const [index, part] of parts.entries()) {
    current = path.join(current, part);
    let stat;
    try { stat = fs.lstatSync(current); }
    catch (error) { if (error.code === 'ENOENT') continue; throw error; }
    if (stat.isSymbolicLink()) throw new Error(`Documentation path contains a symbolic link: ${route}.`);
    if (index < parts.length - 1 && !stat.isDirectory()) throw new Error(`Documentation ancestor is not a directory: ${route}.`);
  }
  return current;
}
function rootPath(root) {
  const absolute = fs.realpathSync(path.resolve(root));
  if (!fs.statSync(absolute).isDirectory()) throw new Error('Documentation root must be a directory.');
  return absolute;
}
function validateConfig(config) {
  for (const name of ['packageRoot', 'sourceRoot', 'tsconfig']) {
    if (!validRoute(config[name]) || /(?:^|\/)(?:\.docs|_sources|node_modules)(?:\/|$)/.test(config[name])) throw new Error(`Invalid documentation config path ${name}.`);
  }
}
function generated(text) {
  const content = finish(text);
  // Keep the llms.txt H1 first; metadata is adjacent to the opening heading.
  if (content.startsWith('# ')) {
    const newline = content.indexOf('\n');
    return content.slice(0, newline + 1) + '\n' + ownership + '\n' + content.slice(newline + 1);
  }
  return ownership + '\n\n' + content;
}
function owned(route, content, config) {
  if (content.startsWith(ownership + '\n') || new RegExp('^# [^\\n]+\\n(?:\\n)*' + ownership.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '(?:\\n|$)').test(content)) return true;
  if (route === packageReadme(config)) return content.startsWith('<!-- Generated from the root README.md by scripts/documentation.cjs. -->\n');
  return route === 'docs/api/INDEX.md' && /^# [^\n]+\n(?:\n)*<!-- Generated by scripts\/documentation\.cjs from public TypeScript exports\. -->\n/.test(content);
}
/** @param {Diagnostic[]} diagnostics Source-relative diagnostics to report together. */
function failDiagnostics(diagnostics) {
  if (!diagnostics.length) return;
  const sorted = [...new Map(diagnostics.map(item => [JSON.stringify(item), item])).values()]
    .sort((a, b) => compare(a.file, b.file) || a.line - b.line || compare(a.code, b.code) || compare(a.message, b.message));
  throw Object.assign(new Error(sorted.map(item => `${item.file}:${item.line} ${item.code}: ${item.message}`).join('\n')), { diagnostics: sorted });
}
/**
 * Compose all outputs exclusively from versioned source, configuration and dependencies.
 * Contract/type/example validation and local link validation finish before returning.
 * No output is created, changed, or used as a content source.
 * @param {string} root Repository directory (a root symlink alias is permitted).
 * @param {Config} [config] Versioned project constants, defaulting to this repository.
 * @returns {ArtifactSet} Ordinally ordered POSIX keys and canonical UTF-8/LF bytes.
 */
function generateArtifacts(root, config = defaultConfig) {
  root = rootPath(root);
  validateConfig(config);
  for (const route of [config.packageRoot, config.sourceRoot, config.tsconfig, 'README.md', path.posix.join(config.packageRoot, 'package.json')]) checkedPath(root, route);
  const graph = buildApiGraph(root, config);
  const model = buildDocumentationModel(graph, config);
  failDiagnostics([...validateDocumentation(model), ...checkDocumentationExamples(root, model, config)]);
  const sources = discoverEditorialSources(root, config);
  const artifacts = Object.create(null);
  function add(route, text) {
    if (!validRoute(route) || !allowed(route, config)) throw new Error(`Documentation destination is not allowed: ${route}.`);
    if (Object.hasOwn(artifacts, route)) throw new Error(`Documentation destination collision: ${route}.`);
    artifacts[route] = generated(text);
  }
  for (const [route, text] of Object.entries(renderApiPages(model, config))) add(route, text);
  add('docs/api/INDEX.md', renderCatalog(model, config));
  for (const [route, text] of Object.entries(renderEditorialPages(sources, model, config))) add(route, text);
  const rootReadme = fs.readFileSync(checkedPath(root, 'README.md'), 'utf8');
  const resolvedReadme = resolveMarkdown(rootReadme, 'README.md', 'README.md', reference => resolveDocumentationReference(model, reference));
  add(packageReadme(config), renderPackageReadme(resolvedReadme, config));

  const metadataProse = (text, source, publicOrigin) => {
    const resolved = resolveMarkdown(text, source, 'llms.txt', reference => resolveDocumentationReference(model, reference), undefined, publicOrigin);
    const url = (config.repositoryUrl || defaultConfig.repositoryUrl).replace(/\/$/, '').replace(/^https:\/\/github\.com\//, 'https://raw.githubusercontent.com/');
    const ref = config.repositoryRef || defaultConfig.repositoryRef;
    return transformMarkdown(resolved, { link: target => externalTarget(target) ? target : `${url}/${ref}/${target}` });
  };
  const metadataLabel = (text, source) => markdownLabel(metadataProse(text, source));
  /** @type {PublicPage[]} */
  const pages = sources.map(source => ({ route: source.route, area: source.area,
    title: metadataLabel(source.title, source.source), summary: metadataProse(source.summary, source.source) }));
  for (const page of model.pages) {
    const introduction = getPageIntroductions(model, page)[0]?.contract;
    pages.push({ route: page.route, title: page.title, area: 'API reference',
      summary: introduction ? metadataProse(introduction.summary, introduction.source.file, page.route) : '' });
  }
  pages.push({ route: 'docs/api/INDEX.md', title: 'API catalog', summary: 'Public symbols and supported imports.', area: 'API reference' });
  const metadata = JSON.parse(fs.readFileSync(checkedPath(root, path.posix.join(config.packageRoot, 'package.json')), 'utf8'));
  add('llms.txt', renderLlms(pages, metadata, config));
  // Directory README targets are aliases only, never additional link origins.
  // Include the real root editorial README in the validation universe, not output.
  const finalTargets = collectPublicTargets(root, { ...artifacts, 'README.md': rootReadme }, config);
  const linkOrigins = Object.fromEntries(finalTargets.filter(target => target.kind === 'markdown' && target.content !== undefined && /(?:\.md|^llms\.txt)$/.test(target.route))
    .map(target => [target.route, target.content]));
  failDiagnostics(validatePublicLinks(linkOrigins, finalTargets, config));
  const result = Object.fromEntries(Object.keys(artifacts).sort(compare).map(route => [route, artifacts[route]]));
  validateExpected(root, result, config);
  return result;
}
/** Validate every output before comparisons, staging or mutations. */
function validateExpected(root, expected, config) {
  validateConfig(config);
  if (!expected || typeof expected !== 'object' || Array.isArray(expected)) throw new Error('Expected documentation artifacts must be a path/text record.');
  const routes = Object.keys(expected).sort(compare);
  const portable = new Set();
  const inodes = new Set();
  for (const [route, content] of Object.entries(expected)) {
    if (!validRoute(route) || !allowed(route, config)) throw new Error(`Documentation destination is not allowed: ${route}.`);
    const folded = route.normalize('NFC').toLowerCase();
    if (portable.has(folded)) throw new Error(`Documentation destination collision: ${route}.`);
    for (const other of routes) if (other !== route && other.normalize('NFC').toLowerCase().startsWith(folded + '/')) throw new Error(`Documentation destination/ancestor collision: ${route} and ${other}.`);
    portable.add(folded);
    if (typeof content !== 'string' || content.includes('\r') || !content.endsWith('\n') || content.endsWith('\n\n') || Buffer.from(content, 'utf8').toString('utf8') !== content) throw new Error(`Documentation artifact requires canonical UTF-8/LF and one final newline: ${route}.`);
    const absolute = checkedPath(root, route);
    if (fs.existsSync(absolute)) {
      const stat = fs.lstatSync(absolute);
      if (!stat.isFile()) throw new Error(`Documentation destination is not a regular file: ${route}.`);
      const inode = `${stat.dev}:${stat.ino}`;
      if (inodes.has(inode)) throw new Error(`Documentation destinations share a file: ${route}.`);
      inodes.add(inode);
    }
  }
}
/** Discover only admitted files; never follow orphan candidates through symlinks. */
function candidates(root, config) {
  const result = [];
  function walk(route) {
    const absolute = checkedPath(root, route);
    if (!fs.existsSync(absolute)) return;
    for (const entry of fs.readdirSync(absolute, { withFileTypes: true }).sort((a, b) => compare(a.name, b.name))) {
      const child = route + '/' + entry.name;
      if (privateRoute(child)) continue;
      if (entry.isDirectory()) walk(child);
      else if (entry.isFile() && child.endsWith('.md')) result.push(child);
    }
  }
  for (const directory of directories) walk(directory);
  for (const route of ['docs/INDEX.md', 'llms.txt', packageReadme(config)]) {
    const absolute = checkedPath(root, route);
    if (fs.existsSync(absolute)) {
      if (!fs.lstatSync(absolute).isFile()) throw new Error(`Documentation destination is not a regular file: ${route}.`);
      result.push(route);
    }
  }
  return result.sort(compare);
}
/**
 * Compare exact expected UTF-8 bytes and find only owned orphans in admitted roots.
 * Reads output bytes for comparison/ownership only; never writes or creates paths.
 * @param {string} root Repository directory.
 * @param {ArtifactSet} expected Complete expected output set.
 * @param {Config} [config] Same versioned constants used for composition.
 * @returns {ArtifactDiff} Ordinally sorted missing/changed/orphan paths.
 */
function compareArtifacts(root, expected, config = defaultConfig) {
  root = rootPath(root);
  validateExpected(root, expected, config);
  const diff = { missing: [], changed: [], orphan: [] };
  for (const route of Object.keys(expected).sort(compare)) {
    const absolute = checkedPath(root, route);
    if (!fs.existsSync(absolute)) diff.missing.push(route);
    else if (!fs.readFileSync(absolute).equals(Buffer.from(expected[route], 'utf8'))) diff.changed.push(route);
  }
  for (const route of candidates(root, config)) if (!Object.hasOwn(expected, route) && owned(route, fs.readFileSync(checkedPath(root, route), 'utf8'), config)) diff.orphan.push(route);
  return diff;
}
/**
 * Check is strictly read-only, including failed checks and directory mtimes.
 * Write stages all changed/missing file bytes first, then replaces each file and
 * removes owned orphans. Unchanged files keep their mtimes. Individual renames
 * are atomic on the repository filesystem; intermediate I/O failure can leave
 * earlier replacements applied, so this is not an all-files transaction. The
 * checkout must not be concurrently modified while applying the set.
 * @param {string} root Repository directory.
 * @param {ArtifactSet} expected Validated complete output set.
 * @param {'write'|'check'} mode Operation.
 * @param {Config} [config] Same versioned constants used for composition.
 * @returns {ArtifactResult} Freshness in check; applied original diff in write.
 */
function applyArtifacts(root, expected, mode, config = defaultConfig) {
  if (mode !== 'write' && mode !== 'check') throw new Error(`Unknown documentation artifact mode: ${mode}.`);
  root = rootPath(root);
  const diff = compareArtifacts(root, expected, config);
  const stale = diff.missing.length + diff.changed.length + diff.orphan.length > 0;
  if (mode === 'check' || !stale) return { ok: !stale, mode, diff };
  const stage = fs.mkdtempSync(path.join(root, '.documentation-stage-'));
  try {
    const writes = [...diff.missing, ...diff.changed].sort(compare);
    for (const [index, route] of writes.entries()) fs.writeFileSync(path.join(stage, String(index)), expected[route], { encoding: 'utf8', flag: 'wx' });
    for (const [index, route] of writes.entries()) {
      const destination = checkedPath(root, route);
      fs.mkdirSync(path.dirname(destination), { recursive: true });
      // Recheck after directory creation and before each replacement/removal.
      fs.renameSync(path.join(stage, String(index)), checkedPath(root, route));
    }
    for (const route of diff.orphan) fs.unlinkSync(checkedPath(root, route));
  } finally { fs.rmSync(stage, { recursive: true, force: true }); }
  return { ok: true, mode, diff };
}
module.exports = { generateArtifacts, compareArtifacts, applyArtifacts };
