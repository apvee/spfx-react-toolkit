const fs = require('node:fs');
const path = require('node:path');
const defaultConfig = require('./documentation.config.cjs');
const { getPageIntroductions, resolveDocumentationReference } = require('./documentation-contract.cjs');
const { buildValidatedDocumentationContext, failDiagnostics, validateConfig } = require('./documentation-context.cjs');
const { validRoute, rootPath, checkedPath, preflightGeneratedArtifacts, compareGeneratedArtifacts, applyGeneratedArtifacts } = require('./generated-artifacts.cjs');
const { renderApiPages, renderCatalog, renderPackageReadme, renderLlms } = require('./documentation-render.cjs');
const { discoverEditorialSources, renderEditorialPages, collectPublicTargets, validatePublicLinks } = require('./documentation-guides.cjs');
const { markdownLabel, resolveMarkdown, transformMarkdown, externalTarget } = require('./documentation-markdown.cjs');

/** @typedef {import('./documentation-model.cjs').Config} Config */
/** @typedef {import('./documentation-model.cjs').Diagnostic} Diagnostic */
/** @typedef {import('./documentation-render.cjs').PublicPage} PublicPage */
/** @typedef {Record<string, string>} ArtifactSet Repository-relative POSIX paths to canonical UTF-8/LF text. */
/** @typedef {{missing: string[], changed: string[], orphan: string[]}} ArtifactDiff Sorted output differences. */
/** @typedef {{ok: boolean, mode: 'write'|'check', diff: ArtifactDiff}} ArtifactResult Write returns the applied diff; check returns freshness without mutation. */
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0;
const finish = text => text.replace(/\r\n?/g, '\n').replace(/\n*$/, '\n');
const ownership = '<!-- Generated by scripts/documentation.cjs. Do not edit. -->';
const directories = ['docs/api', 'docs/getting-started', 'docs/guides', 'docs/development'];
const packageReadme = config => path.posix.join(config.packageRoot, 'README.md');

const privateRoute = route => /(?:^|\/)(?:\.docs|_sources|node_modules|\.git)(?:\/|$)/.test(route);
function allowed(route, config) {
  if (privateRoute(route)) return false;
  return route === 'llms.txt' || route === 'docs/INDEX.md' || route === packageReadme(config) ||
    directories.some(directory => route.startsWith(directory + '/') && route.endsWith('.md'));
}
function generated(text) {
  const content = finish(text);
  // Keep the llms.txt H1 first; metadata is adjacent to the opening heading.
  if (content.startsWith('# ')) {
    const newline = content.indexOf('\n');
    return content.slice(0, newline + 1) + '\n' + ownership + '\n' + content.slice(newline + 1);
  }
  return ownership + '\n\n' + content;
}
function owned(route, content, config) {
  if (content.startsWith(ownership + '\n') || new RegExp('^# [^\\n]+\\n(?:\\n)*' + ownership.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '(?:\\n|$)').test(content)) return true;
  if (route === packageReadme(config)) return content.startsWith('<!-- Generated from the root README.md by scripts/documentation.cjs. -->\n');
  return route === 'docs/api/INDEX.md' && /^# [^\n]+\n(?:\n)*<!-- Generated by scripts\/documentation\.cjs from public TypeScript exports\. -->\n/.test(content);
}
/**
 * Compose all outputs exclusively from versioned source, configuration and dependencies.
 * Contract/type/example validation and local link validation finish before returning.
 * No output is created, changed, or used as a content source.
 * @param {string} root Repository directory (a root symlink alias is permitted).
 * @param {Config} [config] Versioned project constants, defaulting to this repository.
 * @returns {ArtifactSet} Ordinally ordered POSIX keys and canonical UTF-8/LF bytes.
 */
function generateArtifacts(root, config = defaultConfig) {
  return renderDocumentationArtifacts(root, buildValidatedDocumentationContext(root, config), config);
}
/** Render documents and validate public links using an already validated context.
 * Does not rebuild the canonical model or repeat source contract/example checking.
 * @param {string} root Repository root.
 * @param {import('./documentation-context.cjs').DocumentationContext} context Shared canonical graph/model.
 * @param {Config} [config] Same versioned configuration used for the context.
 * @returns {ArtifactSet} Complete canonical document set.
 */
function renderDocumentationArtifacts(root, context, config = defaultConfig) {
  root = rootPath(root);
  const { model } = context;
  const sources = discoverEditorialSources(root, config);
  const artifacts = Object.create(null);
  function add(route, text) {
    if (!validRoute(route) || !allowed(route, config)) throw new Error(`Documentation destination is not allowed: ${route}.`);
    if (Object.hasOwn(artifacts, route)) throw new Error(`Documentation destination collision: ${route}.`);
    artifacts[route] = generated(text);
  }
  for (const [route, text] of Object.entries(renderApiPages(model, config))) add(route, text);
  add('docs/api/INDEX.md', renderCatalog(model, config));
  for (const [route, text] of Object.entries(renderEditorialPages(sources, model, config))) add(route, text);
  const rootReadme = fs.readFileSync(checkedPath(root, 'README.md'), 'utf8');
  const resolvedReadme = resolveMarkdown(rootReadme, 'README.md', 'README.md', reference => resolveDocumentationReference(model, reference));
  add(packageReadme(config), renderPackageReadme(resolvedReadme, config));

  const metadataProse = (text, source, publicOrigin) => {
    const resolved = resolveMarkdown(text, source, 'llms.txt', reference => resolveDocumentationReference(model, reference), undefined, publicOrigin);
    const url = (config.repositoryUrl || defaultConfig.repositoryUrl).replace(/\/$/, '').replace(/^https:\/\/github\.com\//, 'https://raw.githubusercontent.com/');
    const ref = config.repositoryRef || defaultConfig.repositoryRef;
    return transformMarkdown(resolved, { link: target => externalTarget(target) ? target : `${url}/${ref}/${target}` });
  };
  const metadataLabel = (text, source) => markdownLabel(metadataProse(text, source));
  /** @type {PublicPage[]} */
  const pages = sources.map(source => ({ route: source.route, area: source.area,
    title: metadataLabel(source.title, source.source), summary: metadataProse(source.summary, source.source) }));
  for (const page of model.pages) {
    const introduction = getPageIntroductions(model, page)[0]?.contract;
    pages.push({ route: page.route, title: page.title, area: 'API reference',
      summary: introduction ? metadataProse(introduction.summary, introduction.source.file, page.route) : '' });
  }
  pages.push({ route: 'docs/api/INDEX.md', title: 'API catalog', summary: 'Public symbols and supported imports.', area: 'API reference' });
  const metadata = JSON.parse(fs.readFileSync(checkedPath(root, path.posix.join(config.packageRoot, 'package.json')), 'utf8'));
  add('llms.txt', renderLlms(pages, metadata, config));
  // Directory README targets are aliases only, never additional link origins.
  // Include the real root editorial README in the validation universe, not output.
  const finalTargets = collectPublicTargets(root, { ...artifacts, 'README.md': rootReadme }, config);
  const linkOrigins = Object.fromEntries(finalTargets.filter(target => target.kind === 'markdown' && target.content !== undefined && /(?:\.md|^llms\.txt)$/.test(target.route))
    .map(target => [target.route, target.content]));
  failDiagnostics(validatePublicLinks(linkOrigins, finalTargets, config));
  const result = Object.fromEntries(Object.keys(artifacts).sort(compare).map(route => [route, artifacts[route]]));
  preflightGeneratedArtifacts(root, result, documentationPolicy(config));
  return result;
}
/** Destination/ownership rules shared by standalone and unified composition. */
function documentationPolicy(config = defaultConfig) {
  validateConfig(config);
  return { allows: route => allowed(route, config), owns: (route, text) => owned(route, text, config),
    candidateRoots: [...directories, 'docs/INDEX.md', 'llms.txt', packageReadme(config)], replaceUnownedExpected: true };
}
/** Compare expected documentation without writing. @returns {ArtifactDiff} */
function compareArtifacts(root, expected, config = defaultConfig) {
  return compareGeneratedArtifacts(root, expected, documentationPolicy(config));
}
/** Check or apply canonical documentation using its historical ownership policy. @returns {ArtifactResult} */
function applyArtifacts(root, expected, mode, config = defaultConfig) {
  return applyGeneratedArtifacts(root, expected, mode, documentationPolicy(config));
}
module.exports = { generateArtifacts, renderDocumentationArtifacts, documentationPolicy, compareArtifacts, applyArtifacts };
